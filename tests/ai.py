"""仅针对独立测试服务器的本地模拟模型，不使用生产模型。"""
import time
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser = p.chromium.launch(channel="msedge", headless=True)
    page = browser.new_page(viewport={"width": 1500, "height": 1200})
    page.goto("http://127.0.0.1:5189")
    page.wait_for_load_state("networkidle")
    page.get_by_label("手机号").fill("13900001234")
    page.get_by_label("密码", exact=True).fill("MarkerTest123!")
    page.get_by_role("button", name="登录工作区").click()
    page.get_by_role("button", name="新建项目").click()
    page.get_by_label("项目名称").fill("AI浏览器-" + str(int(time.time())))
    page.get_by_label("标签集").fill("正向,负向")
    page.get_by_role("button", name="确认保存").click()
    page.get_by_role("button", name="导入数据", exact=True).click()
    page.get_by_label("数据集名称").fill("测试集")
    page.get_by_label("文本内容", exact=True).fill("AI-ok")
    page.once("dialog", lambda d: d.accept())
    page.get_by_role("button", name="确认保存").click()
    page.get_by_role("button", name="关闭", exact=True).click()
    page.get_by_role("link", name="标注任务").click()
    page.get_by_label("选择本页", exact=True).check()
    page.locator(".ai-panel summary").click()
    page.once("dialog", lambda d: d.accept())
    page.get_by_role("button", name="预标注选中任务（1）").click()
    expect(page.locator(".job b").first).to_contain_text("已完成", timeout=15000)
    page.get_by_role("button", name="刷新预测和任务").click()
    page.get_by_role("button", name="AI-ok", exact=False).click()
    expect(page.get_by_label("正向", exact=True)).not_to_be_checked()
    page.get_by_role("button", name="采用预测为草稿", exact=True).click()
    expect(page.get_by_label("正向", exact=True)).to_be_checked()
    expect(page.locator(".task-detail .status")).to_have_text("标注中")
    expect(page.get_by_role("status")).to_have_text("已保存")
    page.reload()
    page.get_by_role("button", name="AI-ok", exact=False).click()
    expect(page.get_by_label("正向", exact=True)).to_be_checked()
    browser.close()
    print("PASS: 本地模型任务提交、状态轮询、预测与人工分离、显式采用、持久化回读")
