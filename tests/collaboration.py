"""分页、批量任务、抽检、项目设置及成员页面联调。"""
import time
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser = p.chromium.launch(channel="msedge", headless=True)
    page = browser.new_page(viewport={"width": 1600, "height": 1100})
    page.goto("http://127.0.0.1:5189")
    page.wait_for_load_state("networkidle")
    page.get_by_label("手机号").fill("13900001234")
    page.get_by_label("密码", exact=True).fill("MarkerTest123!")
    page.get_by_role("button", name="登录工作区").click()
    expect(page.get_by_role("button", name="新建项目")).to_be_visible()
    token = page.evaluate("localStorage.getItem('token')")
    def req(path, data=None):
        r = page.request.post("http://127.0.0.1:5189/api/" + path, data=data, headers={"token": token}) if data is not None else page.request.get("http://127.0.0.1:5189/api/" + path, headers={"token": token})
        assert r.status == 200, r.text()
        return r.json()["data"]
    project = req("annotation/projects", {"name": "协作浏览器-" + str(int(time.time())), "type": "text", "labels": ["正向"]})
    root = "annotation/projects/" + project["_id"]
    req(root + "/import", {"dataset": "分页集", "items": ["协作文本" + str(i) for i in range(25)]})
    sample = req(root + "/samples")["items"][0]
    sample = req(root + "/samples/" + sample["id"], {"action": "submit", "revision": 0, "annotation": {"labels": ["正向"]}})
    req(root + "/samples/" + sample["id"], {"action": "approve", "revision": sample["revision"]})
    page.goto("http://127.0.0.1:5189/#tasks/" + project["_id"])
    page.wait_for_load_state("networkidle")
    expect(page.locator(".task-row")).to_have_count(20)
    page.get_by_role("button", name="下一页", exact=True).click()
    expect(page.locator(".task-row")).to_have_count(5)
    page.get_by_label("选择本页", exact=True).check()
    page.get_by_label("批量分配人员").select_option(project["ownerId"])
    page.get_by_role("button", name="批量分配 / 回收", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("成功 5 条")
    page.get_by_role("button", name="关闭", exact=True).click()
    page.get_by_role("link", name="审核质检").click()
    page.get_by_role("button", name="随机抽检已通过数据（20 条）", exact=True).click()
    page.get_by_role("button", name="协作文本0", exact=False).click()
    page.get_by_label("抽检问题").fill("边界不符合规范，请返工")
    page.get_by_role("button", name="抽检不通过，退回返工").click()
    expect(page.locator(".task-detail .status")).to_have_text("已驳回")
    page.get_by_role("link", name="项目成员").click()
    page.get_by_label("已注册手机号").fill("13900001235")
    page.get_by_role("button", name="保存成员", exact=True).click()
    expect(page.get_by_text("测试标注员", exact=True)).to_be_visible()
    page.once("dialog", lambda d: d.accept())
    page.get_by_role("button", name="移除成员", exact=True).click()
    expect(page.get_by_text("测试标注员", exact=True)).to_have_count(0)
    page.get_by_role("link", name="项目设置").click()
    page.get_by_label("标注规范", exact=True).fill("浏览器规范验证")
    page.get_by_label("禁止标注者审核自己的结果").check()
    page.get_by_role("button", name="保存项目设置", exact=True).click()
    expect(page.get_by_label("标注规范", exact=True)).to_have_value("浏览器规范验证")
    page.get_by_role("link", name="数据导出").click()
    expect(page.get_by_role("heading", name="操作记录")).to_be_visible()
    browser.close()
    print("PASS: 服务端分页、批量分配、全项目随机抽检返工、添加/移除成员、规范、自审配置、审计页面")
